__all__ = ["SchemaCompileError", "MaskPages", "compile_schema_to_mask_pages", "zero_special_ids"]


class SchemaCompileError(Exception):
    def __init__(self, message: str, *, state_id: int | None = None, prefix: bytes = b"", reason: str = "") -> None:
        super().__init__(message)
        self.state_id = state_id
        self.prefix = prefix
        self.reason = reason


class _StringLeaf:
    __slots__ = ()


_STRING_LEAF = _StringLeaf()
_SHORT_ESCAPE_CHARS = ('"', "\\", "/", "b", "f", "n", "r", "t")
_HEX_DIGITS = "0123456789abcdefABCDEF"
_Group = tuple[Any, ...]

# --- S3 (T-2908, unchanged): the compiler's own accepted-keyword surface, by branch ----------

_ALLOWED_KEYWORDS: dict[str, frozenset[str]] = {
    "enum": frozenset({"enum"}),
    "boolean": frozenset({"type"}),
    "string": frozenset({"type"}),
    "object": frozenset({"type", "properties", "required", "additionalProperties"}),
}

_KEYWORD_REASON_OVERRIDES: dict[str, str] = {
    "maxLength": (
        "The ratified rule only requires that no length bound is added to the DFA -- an unbounded "
        "self-loop ships regardless of what value a schema names -- and says nothing about "
        "schema-ingestion; silently accepting the keyword and compiling an unbounded field "
        "anyway would discard the schema author's own stated constraint with no diagnostic, "
        "wrong independent of whether the bound is ever implemented (T-2859 F2, D-SLM7462)"
    ),
}


def _reject_unimplemented_keywords(schema: Mapping[str, Any], path: str, allowed: frozenset[str]) -> None:
    for key in sorted(schema):
        if key in allowed:
            continue
        reason = _KEYWORD_REASON_OVERRIDES.get(key, (
            f"{key!r} is a JSON-Schema keyword this compiler does not implement; a schema "
            f"naming it is rejected rather than silently accepted with the constraint "
            f"unenforced (generalizes the maxLength precedent, T-2859 F2/S3, to every "
            f"keyword outside {sorted(allowed)!r})"
        ))
        raise SchemaCompileError(f"{key} is not supported at {path}", reason=reason)


def _groups(schema: Mapping[str, Any], path: str) -> list[_Group]:
    if "enum" in schema:
        _reject_unimplemented_keywords(schema, path, _ALLOWED_KEYWORDS["enum"])
        values = schema["enum"]
        if not values:
            raise SchemaCompileError(f"empty enum at {path}", reason=f"empty enum at {path}")
        return [tuple(json.dumps(v, ensure_ascii=False) for v in values)]

    node_type = schema.get("type")

    if node_type == "boolean":
        _reject_unimplemented_keywords(schema, path, _ALLOWED_KEYWORDS["boolean"])
        return [("true", "false")]

    if node_type == "string":
        _reject_unimplemented_keywords(schema, path, _ALLOWED_KEYWORDS["string"])
        return [(_STRING_LEAF,)]

    if node_type == "object":
        _reject_unimplemented_keywords(schema, path, _ALLOWED_KEYWORDS["object"])
        properties = schema.get("properties") or {}
        required = list(schema.get("required", list(properties)))
        if schema.get("additionalProperties", False) is not False:
            raise SchemaCompileError(
                f"object at {path} permits additional properties",
                reason="additionalProperties must be false; an open object has no fixed serialization",
            )
        if required != list(properties):
            raise SchemaCompileError(
                f"object at {path} has optional or reordered keys",
                reason="every property must be required, in properties order (D-SLM45); optional/reordered keys are outside the compilable subset",
            )
        groups: list[_Group] = [("{",)]
        for index, (key, sub_schema) in enumerate(properties.items()):
            if index:
                groups.append((",",))
            groups.append((json.dumps(key, ensure_ascii=False) + ":",))
            groups.extend(_groups(sub_schema, f"{path}.{key}"))
        groups.append(("}",))
        return groups

    raise SchemaCompileError(
        f"unsupported construct at {path}",
        reason=f"type {node_type!r} is outside D-SLM45's compilable subset (objects with known keys, enums, booleans, unbounded free-text strings; cross-field constraints are scored, not compiled)",
    )


# --- S2 (T-2908, unchanged): the byte-level content sub-automaton ---------------------------


def _add_string_leaf(edges: list[dict[int, set[int]]], add_node: Callable[[], int], cursor: int,
                      content_nodes: set[int]) -> int:
    """T-2853's cyclic sub-automaton, over raw bytes (T-2908). Every interior node this function
    creates -- S_c itself, the escape branch, the hex chain, and every UTF-8 lead/continuation
    state -- is recorded in `content_nodes` (T-2910) so `_char_dfa` can label which DFA states
    belong to the content region once subset construction has run. `following` (the state exited
    to) and `cursor` (the state entered from) are NOT content nodes -- they are the schema's own
    literal skeleton on either side of this leaf."""
    s_c = add_node()
    content_nodes.add(s_c)
    edges[cursor].setdefault(0x22, set()).add(s_c)  # opening quote

    quote, backslash = 0x22, 0x5C

    def edge(state: int, lo: int, hi: int, target: int) -> None:
        for b in range(lo, hi + 1):
            edges[state].setdefault(b, set()).add(target)

    # Ordinary single-byte ASCII content: not '"', not '\', not a C0 control (0x00-0x1F).
    edge(s_c, 0x20, quote - 1, s_c)
    edge(s_c, quote + 1, backslash - 1, s_c)
    edge(s_c, backslash + 1, 0x7F, s_c)

    # Multi-byte UTF-8 lead bytes, each routed to a state whose admitted continuation range
    # excludes the overlong/surrogate/out-of-range spellings the plain 0x80-0xBF range would
    # otherwise let through.
    lead2 = add_node(); content_nodes.add(lead2)
    edge(s_c, 0xC2, 0xDF, lead2)  # 0xC0-0xC1 (overlong) and bare continuation bytes: no edge
    edge(lead2, 0x80, 0xBF, s_c)

    lead3_a, lead3_b, lead3_c, mid3 = add_node(), add_node(), add_node(), add_node()
    for n in (lead3_a, lead3_b, lead3_c, mid3):
        content_nodes.add(n)
    edge(s_c, 0xE0, 0xE0, lead3_a)
    edge(s_c, 0xE1, 0xEC, lead3_b)
    edge(s_c, 0xED, 0xED, lead3_c)
    edge(s_c, 0xEE, 0xEF, lead3_b)
    edge(lead3_a, 0xA0, 0xBF, mid3)  # excludes the overlong 0x80-0x9F continuation
    edge(lead3_b, 0x80, 0xBF, mid3)
    edge(lead3_c, 0x80, 0x9F, mid3)  # excludes the surrogate range 0xA0-0xBF (U+D800-DFFF)
    edge(mid3, 0x80, 0xBF, s_c)

    lead4_a, lead4_b, lead4_c, mid4a, mid4b = add_node(), add_node(), add_node(), add_node(), add_node()
    for n in (lead4_a, lead4_b, lead4_c, mid4a, mid4b):
        content_nodes.add(n)
    edge(s_c, 0xF0, 0xF0, lead4_a)
    edge(s_c, 0xF1, 0xF3, lead4_b)
    edge(s_c, 0xF4, 0xF4, lead4_c)
    edge(lead4_a, 0x90, 0xBF, mid4a)  # excludes the overlong 0x80-0x8F continuation
    edge(lead4_b, 0x80, 0xBF, mid4a)
    edge(lead4_c, 0x80, 0x8F, mid4a)  # excludes codepoints past U+10FFFF
    edge(mid4a, 0x80, 0xBF, mid4b)
    edge(mid4b, 0x80, 0xBF, s_c)
    # 0xF5-0xFF: no edge (no valid codepoint starts with these bytes).

    s_e = add_node(); content_nodes.add(s_e)
    edges[s_c].setdefault(backslash, set()).add(s_e)
    for escape_char in _SHORT_ESCAPE_CHARS:
        edges[s_e].setdefault(ord(escape_char), set()).add(s_c)

    hex_states = [add_node() for _ in range(4)]
    content_nodes.update(hex_states)
    edges[s_e].setdefault(ord("u"), set()).add(hex_states[0])
    for index, state in enumerate(hex_states):
        target = hex_states[index + 1] if index + 1 < len(hex_states) else s_c
        for digit in _HEX_DIGITS:
            edges[state].setdefault(ord(digit), set()).add(target)

    following = add_node()  # NOT a content node: the literal skeleton resumes here.
    edges[s_c].setdefault(quote, set()).add(following)
    return following


def _char_dfa(groups: Sequence[_Group]) -> tuple[list[dict[int, int]], int, frozenset[int], frozenset[int]]:
    """Returns (dfa, start, accepting, content_states) -- content_states (T-2910) is the fourth
    element, additive to T-2908's three-tuple; every caller in this module is updated for it."""
    edges: list[dict[int, set[int]]] = [{}]
    content_nodes: set[int] = set()

    def add_node() -> int:
        edges.append({})
        return len(edges) - 1

    cursor = 0
    for group in groups:
        if len(group) == 1 and group[0] is _STRING_LEAF:
            cursor = _add_string_leaf(edges, add_node, cursor, content_nodes)
            continue
        following = add_node()
        for alternative in group:
            if not alternative:
                raise SchemaCompileError(
                    "an alternation contains the empty string",
                    reason="a zero-length alternative makes the serialization ambiguous",
                )
            raw = alternative.encode("utf-8")
            node = cursor
            for index, byte_val in enumerate(raw):
                target = following if index == len(raw) - 1 else add_node()
                edges[node].setdefault(byte_val, set()).add(target)
                node = target
        cursor = following
    accept_node = cursor

    start_set = frozenset({0})
    ids: dict[frozenset[int], int] = {start_set: 0}
    dfa: list[dict[int, int]] = [{}]
    accepting: set[int] = set()
    content_states: set[int] = set()
    queue: deque[frozenset[int]] = deque([start_set])
    while queue:
        current = queue.popleft()
        state = ids[current]
        if accept_node in current:
            accepting.add(state)
        if current & content_nodes:
            content_states.add(state)
        moves: dict[int, set[int]] = {}
        for node in current:
            for byte_val, targets in edges[node].items():
                moves.setdefault(byte_val, set()).update(targets)
        row: dict[int, int] = {}
        for byte_val in sorted(moves):
            target_set = frozenset(moves[byte_val])
            if target_set not in ids:
                ids[target_set] = len(dfa)
                dfa.append({})
                queue.append(target_set)
            row[byte_val] = ids[target_set]
        dfa[state] = row
    return dfa, 0, frozenset(accepting), frozenset(content_states)


def _shortest_completion(dfa: Sequence[Mapping[int, int]], accepting: frozenset[int], state: int) -> bytes:
    seen = {state}
    queue: deque[tuple[int, bytes]] = deque([(state, b"")])
    while queue:
        current, data = queue.popleft()
        if current in accepting:
            return data
        for byte_val in sorted(dfa[current]):
            target = dfa[current][byte_val]
            if target not in seen:
                seen.add(target)
                queue.append((target, data + bytes([byte_val])))
    return b""


class _TrieNode:
    __slots__ = ("children", "token_id")

    def __init__(self) -> None:
        self.children: dict[int, _TrieNode] = {}
        self.token_id: int | None = None


def _vocab_trie(vocab: Sequence[bytes]) -> _TrieNode:
    root = _TrieNode()
    for token_id, piece in enumerate(vocab):
        if not piece:
            continue
        node = root
        for byte_val in piece:
            child = node.children.get(byte_val)
            if child is None:
                child = _TrieNode()
                node.children[byte_val] = child
            node = child
        if node.token_id is None:
            node.token_id = token_id
    return root


def zero_special_ids(vocab: Sequence[bytes], special_ids: frozenset[int]) -> list[bytes]:
    """T-2910 S4 (folding TE-366 group 2). Zeroes every special/added token id's bytes so
    `_vocab_trie`'s existing empty-piece guard excludes it -- structurally, for every state of
    every schema this compiler ever compiles, not only the string leaf. Applied to the vocabulary
    BEFORE `compile_schema_to_mask_pages` ever sees it; the compiler itself takes no special-id
    parameter, so there is no second place a caller could forget to pass one."""
    out = list(vocab)
    for i in special_ids:
        if 0 <= i < len(out):
            out[i] = b""
    return out


# T-2911 (D-SLM7590, folding TE-367's FRACTURE of T-2910's asymmetric rule): the exact set of
# bytes `_groups()` (T-2908, unchanged) ever emits as object-skeleton literal punctuation --
# derived at source, not from the six spellings TE-367's own census happened to observe. `_groups()`
# emits `{` and `}` for every object's own open/close literal, and `:`/`,` inside the literal
# key-and-separator text it builds for each property (`f"{json.dumps(key)}:"`, and a `(",",)` group
# between properties). `_groups()` raises `SchemaCompileError` for `"type": "array"` at every call
# site that reaches it (S3's allowlist), so `[`/`]` are never emitted by this compiler and are
# excluded on that ground -- not because a lone bracket is semantically harmless as content, but
# because this compiler's own grammar has never had a reason to admit one as skeleton punctuation.
# `}` is included even though TE-367 named no `}"` instance: it is the same object-skeleton literal
# `{` is, emitted by the same `_groups()` group, and a set derived from the grammar the compiler
# actually emits does not omit one half of a literal pair because a 40-prompt sample never selected
# it. If a future schema type reintroduces `[`/`]` as compilable skeleton punctuation, this set is
# re-derived against the grammar at that time, not silently assumed to extend.
_STRUCTURAL_CLOSE_BYTES: frozenset[int] = frozenset({0x7B, 0x7D, 0x2C, 0x3A})  # { } , :


def _token_targets(dfa: Sequence[Mapping[int, int]], state: int, root: _TrieNode,
                    content_states: frozenset[int],
                    structural_close_bytes: frozenset[int] = _STRUCTURAL_CLOSE_BYTES) -> dict[int, int]:
    """T-2911 (D-SLM7590, refining T-2910's asymmetric rule, D-SLM7589, after TE-367 FRACTURED it):
    the two crossing directions still carry different risk and get different treatment, and the
    close side now carries one further distinction TE-367's own census forced.

    OPENING a value (a token transitioning from a NON-content state to a content state) is
    restricted to its own first byte, and a token that opens contributes no further bytes. This is
    the direct occupant of "no token carries pre-value structure into content": the bytes
    immediately after an opening quote are, in the pre-fix design, disproportionately likely to be
    literal/skeleton-shaped (a colon, a brace) precisely because the vocabulary's most probable
    quote-adjacent tokens are JSON-structural, not because the model chose that content -- TE-366's
    own "86 of 267 deposit skeleton punctuation first" and "20 open-and-close in one token" both
    live here, and both require the opening byte to be followed, within the SAME token, by bytes
    the free content walk never got an independent chance to accept or reject. Refusing any byte
    after the open removes that channel entirely: the model chooses its first content byte as its
    own decode step, with the full mask in front of it. UNCHANGED from T-2910.

    CLOSING a value (content to non-content) is walked unrestricted UP TO the refusal below: any
    number of genuine content bytes (each already having passed through the ordinary content walk,
    since they are the SAME bytes an unrestricted content-continuation token would carry) followed
    by the closing byte, followed by zero or more bytes that continue matching the schema's own next
    literal transitions exactly (the trie/DFA co-descent already refuses to extend past a byte with
    no matching row entry, so "everything after the close is valid structure" falls out of the
    existing walk with no extra check). This is T-2910's own rule, UNCHANGED as far as it goes; what
    T-2911 adds is a refusal at the moment of closing, not a narrower walk before it.

    T-2911's OWN refinement (D-SLM7590, folding TE-367's FRACTURE): at the exact byte where a token
    would close (a transition from a content state to a non-content state), refuse the closing
    transition -- and therefore every token reachable only through it -- when this token's OWN
    pre-close content bytes (the bytes this SAME token consumed while still in a content state,
    before the closing byte; NOT the answer's full history across earlier tokens) are non-empty and
    every one of them is a member of `_STRUCTURAL_CLOSE_BYTES` (`{`, `}`, `,`, `:` -- derived in this
    module's own top-level comment from the grammar `_groups()` actually emits, not from the six
    spellings TE-367's census observed). A token whose pre-close content is EMPTY (the bare `"`) is
    unaffected: there is nothing to classify, so the close it always permitted stays permitted. A
    token like `.` + `"` (a sentence's own final period, then the close) or `.` + `"` + `}` (period,
    close, and the object's own final brace in one token) stays admitted: `.` is not a structural
    byte, so "solely structural" is false regardless of what non-structural bytes accompany it. A
    token like `,` + `"` or `{` + `"` is now refused: its one pre-close content byte is a member of
    the structural set and there is nothing else in the token to make the run non-solely-structural.

    An EARLIER version of this function (T-2910, D-SLM7589) left the close side entirely
    unrestricted once past the open-side fix, on the ground that TE-366's own 40-prompt census
    named zero compound-close defects. TE-367 measured that population under the REPLACEMENT rule
    rather than the predecessor it was drawn from and found 27 of 40 real prompts select a
    close-side crossing token, two of which end an accepted non-answer (`,"` at row 21, `{"` at row
    22) -- absence of a defect under a MORE restrictive predecessor was never evidence about a LESS
    restrictive replacement once the replacement changes which tokens are admitted and therefore the
    decode trajectory itself (TE-367's own reconciliation). This refinement removes exactly the
    27-instance close-side crossing rate's structural-only members while leaving the 25
    natural-sentence-ending members (`.`, `?`, `!` before the close) exactly as permissive as
    T-2910 left them, because none of TE-367's stated cost (9 of 40 clean accept under the fully
    symmetric predecessor, against 38 of 40 under T-2910's asymmetric rule) came from a
    structural-only close: TE-367's own 27-row population is dominated by `."` (T-2910's own
    still-permitted case), and only 3 of the 27 rows (`{"`, `:"` x2, `,"`) are structural-only, of
    which only 2 rows are the two that end a non-answer.

    Special/control ids are excluded upstream, in `zero_special_ids` -- unaffected by which
    direction a crossing is walked or by the structural refusal, since a zeroed piece is never in
    the trie for any of the three fixes to reach.

    A token that never crosses the boundary -- wholly inside content (free multi-byte answer
    tokens, unaffected, at full width) or wholly outside it (compound literal-skeleton tokens,
    unaffected, per the design's own existing harmless-crossing precedent) -- is walked exactly as
    T-2908's own function did, on both sides."""
    targets: dict[int, int] = {}
    # stack entries: (trie_node, dfa_state, depth, stop_after, content_run) -- stop_after is True
    # only for a node reached by an OPENING crossing, which may only happen at depth 0 and forbids
    # any further descent; content_run is the tuple of byte values this SAME token has consumed so
    # far while in a content state (never crossing a token boundary), consulted only at the moment
    # of a CLOSING transition and otherwise carried through unchanged.
    stack: list[tuple[_TrieNode, int, int, bool, tuple[int, ...]]] = [(root, state, 0, False, ())]
    while stack:
        node, current, depth, stop_after, content_run = stack.pop()
        if node.token_id is not None:
            targets[node.token_id] = current
        if stop_after:
            continue  # an opening token contributes no further bytes
        row = dfa[current]
        cur_is_content = current in content_states
        if len(row) < len(node.children):
            pairs = ((byte_val, node.children.get(byte_val), target)
                     for byte_val, target in row.items())
        else:
            pairs = ((byte_val, child, row.get(byte_val))
                     for byte_val, child in node.children.items())
        for byte_val, child, target in pairs:
            if child is None or target is None:
                continue
            target_is_content = target in content_states
            opening = (not cur_is_content) and target_is_content
            if opening and depth != 0:
                continue  # opening past the token's first byte is refused outright
            closing = cur_is_content and not target_is_content
            if closing:
                if content_run and all(b in structural_close_bytes for b in content_run):
                    continue  # T-2911: pre-close content is solely structural punctuation, refused
                next_content_run = content_run  # the closing byte itself is not content
            elif cur_is_content:
                next_content_run = content_run + (byte_val,)
            else:
                next_content_run = content_run
            # a CLOSING crossing that survives the check above, and any non-crossing transition,
            # both continue unrestricted -- stop_after stays False for both.
            stack.append((child, target, depth + 1, opening, next_content_run))
    return targets


class MaskPages:
    def __init__(self, vocab: Sequence[bytes], transitions: Mapping[int, Mapping[int, int]], start: int, accepting: frozenset[int]) -> None:
        self.vocab = tuple(vocab)
        self.transitions: dict[int, dict[int, int]] = {s: dict(row) for s, row in transitions.items()}
        self.start = start
        self.accepting = frozenset(accepting)

    def valid_token_ids(self, state: int) -> frozenset[int]:
        return frozenset(self.transitions.get(state, {}))

    def page(self, state: int) -> bytes:
        n_bytes = (len(self.vocab) + 7) // 8
        out = bytearray(n_bytes)
        for token_id in self.transitions.get(state, {}):
            out[token_id >> 3] |= 1 << (token_id & 7)
        return bytes(out)

    def step(self, state: int, token_id: int) -> int:
        return self.transitions[state][token_id]

    def is_accepting(self, state: int) -> bool:
        return state in self.accepting

    def accepts(self, b: bytes) -> bool:
        state = self.start
        pos = 0
        n = len(b)
        while pos < n:
            row = self.transitions.get(state, {})
            best: tuple[bytes, int] | None = None
            for token_id, next_state in row.items():
                piece = self.vocab[token_id]
                if piece and b.startswith(piece, pos):
                    if best is None or len(piece) > len(best[0]):
                        best = (piece, next_state)
            if best is None:
                return False
            piece, state = best
            pos += len(piece)
        return state in self.accepting


def compile_schema_to_mask_pages(schema: Mapping[str, Any], vocab: Sequence[bytes]) -> MaskPages:
    vocab = tuple(vocab)
    char_dfa, char_start, char_accepting, content_states = _char_dfa(_groups(schema, "$"))
    trie = _vocab_trie(vocab)

    ids: dict[int, int] = {char_start: 0}
    prefixes: dict[int, bytes] = {0: b""}
    transitions: dict[int, dict[int, int]] = {}
    accepting: set[int] = set()
    queue: deque[int] = deque([char_start])
    while queue:
        current = queue.popleft()
        state = ids[current]
        if current in char_accepting:
            accepting.add(state)
        targets = _token_targets(char_dfa, current, trie, content_states)
        if not targets and current not in char_accepting:
            prefix = prefixes[state]
            completion = _shortest_completion(char_dfa, char_accepting, current)
            reason = (
                f"no token in the vocabulary can spell the required continuation {completion!r} "
                f"after the serialization prefix {prefix!r}"
            )
            raise SchemaCompileError(f"state {state} has an empty valid-token set: {reason}", state_id=state, prefix=prefix, reason=reason)
        row: dict[int, int] = {}
        for token_id in sorted(targets):
            target = targets[token_id]
            if target not in ids:
                ids[target] = len(ids)
                prefixes[ids[target]] = prefixes[state] + vocab[token_id]
                queue.append(target)
            row[token_id] = ids[target]
        transitions[state] = row

    return MaskPages(vocab, transitions, 0, frozenset(accepting))
