"""Emit tests/silu_lut_golden_table.h and include/superslm/silu_lut_canonical.h — the
canonical SIL1 sigmoid table (as the converter emits it: numpy float64 round-half-even)
pinned as an in-tree C++ literal, in two places for two different consumers:

- tests/silu_lut_golden_table.h: the S2.4 golden-hash test (test_main.cpp) hashes
  SiluSigmoidQ15's outputs over a canonical input set to prove the RUNTIME construction
  is bit-identical across toolchains/ISAs (and, via the run-only GPU package, across
  vendors).
- include/superslm/silu_lut_canonical.h: the PRODUCTION content-pinning check
  (ParseSigmoidLut, src/model.cpp, S-HARDEN-1/F20). A structurally valid SIL1 section can
  still carry hostile node values (F20/F22's UB chain), and SIL1 is a universal
  construction table the spec fixes entirely — so the loader rejects any SIL1 payload that
  is not byte-for-byte the canonical table, rather than trusting per-node predicates.

Both tables must be a PINNED input, not regenerated by std::exp at load/test time: a libm
difference across platforms would either be a FALSE determinism break (tests) or a FALSE
rejection of a legitimate artifact on some toolchain (production) — the same host-dependency
class F8 names for the tokenizer's Unicode tables. Pinning the converter's exact table keeps
both checks host-independent.

Run from tools/:  python gen_silu_lut_golden.py
"""
import pathlib
import sslm_model_writer as w

HERE = pathlib.Path(__file__).parent
OUT_TEST = HERE.parent / "tests" / "silu_lut_golden_table.h"
OUT_PROD = HERE.parent / "include" / "superslm" / "silu_lut_canonical.h"


def _render(vals, guard, namespace, array_name, header_comment_lines):
    lines = list(header_comment_lines) + [
        f"#ifndef {guard}",
        f"#define {guard}",
        "#include <cstdint>",
        f"namespace {namespace} {{",
        f"inline constexpr int32_t {array_name}[1025] = {{",
    ]
    for i in range(0, len(vals), 16):
        lines.append("\t" + ", ".join(vals[i:i + 16]) + ",")
    lines += ["};", f"}}  // namespace {namespace}", "#endif"]
    text = "\n".join(lines) + "\n"
    # Pure ASCII, written as UTF-8 with an explicit newline. Both halves are load-bearing
    # for the byte-for-byte reproducibility this pinned table depends on: write_text with no
    # encoding= uses the platform's locale encoding, so a single non-ASCII character would
    # serialize to different bytes on a Windows host (cp1252) than on a Linux one (UTF-8)
    # for an unchanged table, and would raise outright under a C/POSIX locale. Asserting
    # ASCII here means the property cannot lapse by someone adding a typographic character
    # to a comment above. (Same defect and same fix as tools/gen_matmul_golden.py.)
    text.encode("ascii")  # raises UnicodeEncodeError if a non-ASCII character crept in
    return text


def main():
    t = w.build_sigmoid_lut()
    assert t.size == 1025 and str(t.dtype) == "int32", (t.size, t.dtype)
    vals = [str(int(x)) for x in t]

    test_text = _render(
        vals, "SUPERSLM_TESTS_SILU_LUT_GOLDEN_TABLE_H", "superslm_test", "kSiluLutGoldenTable",
        [
            "// Auto-generated by tools/gen_silu_lut_golden.py (build_sigmoid_lut, N=1024, X=16, Q15).",
            "// The CANONICAL SIL1 table as the converter emits it (numpy float64 round-half-even).",
            "// Pinned as data so the golden-hash test isolates the RUNTIME construction from libm:",
            "// the runtime reads fixed table bytes, never std::exp, so the golden must too.",
        ])
    OUT_TEST.write_text(test_text, newline="\n", encoding="utf-8")

    prod_text = _render(
        vals, "SUPERSLM_SILU_LUT_CANONICAL_H", "superslm", "kSiluLutCanonicalTable",
        [
            "// Auto-generated by tools/gen_silu_lut_golden.py (build_sigmoid_lut, N=1024, X=16, Q15).",
            "// The canonical SIL1 table (numpy float64 round-half-even) -- the pinned reference",
            "// ParseSigmoidLut (src/model.cpp) validates every loaded SIL1 section against, byte-for-byte.",
            "// SIL1 is a universal construction the format fixes entirely, so any node that differs from",
            "// this table is rejected at load, never evaluated -- a hostile table cannot reach",
            "// SiluSigmoidQ15's interpolation.",
        ])
    OUT_PROD.parent.mkdir(parents=True, exist_ok=True)
    OUT_PROD.write_text(prod_text, newline="\n", encoding="utf-8")

    print(f"wrote {OUT_TEST} (1025 entries; table[0]={t[0]}, table[512]={t[512]}, table[1024]={t[1024]})")
    print(f"wrote {OUT_PROD} (1025 entries; table[0]={t[0]}, table[512]={t[512]}, table[1024]={t[1024]})")


if __name__ == "__main__":
    main()
