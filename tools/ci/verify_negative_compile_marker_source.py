"""T-2142 (Claude/Poirot/aea6116-t2139-seventh-confirmation-review.md M1, the residual half):
"M1's other half is open and recorded as closed: a partially-mangled marker still passes
vacuously." The empty-marker guard in tools/ci/check_negative_compile_marker.cmake closed the
empty case; a MANGLED marker -- a one-character transcription, a truncated tail from
CMakeLists.txt's own backslash-escaped hand transcription -- still satisfies a plain substring
search against the compiler's captured output, because any short fragment of a real message is
itself present in that message.

Executed against HEAD before this fix existed (T-2142's own owed-item validation): TWO of the
four -DMARKER_TEXT= values already IN CMakeLists.txt were themselves truncated fragments of
their construction's own full static_assert message -- not a hypothetical mangling, a real one:
  - t2139_gate_c_xmacro_must_reject_fails_to_compile's marker was
    "SSLM_ARTIFACT_REJECTED diverges", missing the macro-generated suffix
    " (deliberate corruption, must-reject construction)" every other must-reject entry that goes
    through the SAME per-name macro shape carries.
  - t2139_gate_c_sentinel_must_reject_fails_to_compile's marker was
    "SSLM_STATUS_NEXT_FREE sentinels no longer agree", missing the prefix
    "registry-top divergence (deliberate one-sided append, must-reject construction): the two ".
Both passed every existing check (build failed, marker found by substring search) while being
demonstrably incomplete -- exactly M1's own "not any substring of it" requirement.

This script closes the class: given a target's own SOURCE FILE and the -DMARKER_TEXT= value
check_negative_compile_marker.cmake was invoked with, it derives the FULL set of static_assert
messages that source file can actually produce and requires MARKER_TEXT to equal one of them
EXACTLY -- not merely appear as a substring of the source, which "e" or any short fragment would
trivially satisfy too.

Two message shapes are handled, matching every must-reject construction in this repo today:
  1. A literal static_assert(cond, "message") -- possibly split across adjacent string-literal
     concatenation -- extracted and concatenated verbatim.
  2. A macro-templated static_assert generated by X-macro expansion, whose message is built from
     the stringized parameter (`#NAME`) followed by a literal suffix (`#NAME " suffix text"`).
     Since the raw source text never shows the expanded name (the X-macro expansion happens in
     the compiler, not in this script), every ALL-CAPS SSLM_*-shaped identifier appearing
     anywhere else in the file is accepted as a candidate NAME, and MARKER_TEXT is valid if it
     equals `NAME + suffix` for some candidate NAME and some captured suffix. This does not
     claim to know WHICH name the corruption targets (that is MARKER_TEXT's own job to assert);
     it only refuses a message that is not a complete, well-formed instance of the construction's
     own message shape.

Exit 0 (valid, full message) or 1 (mangled / not derivable from the source) with the reason
printed either way.
"""
import re
import sys

STRING_LITERAL = r'"(?:[^"\\]|\\.)*"'


def unescape(raw_literal_body):
	# raw_literal_body has already had its surrounding quotes stripped by the caller.
	return raw_literal_body.replace('\\"', '"').replace('\\n', '\n').replace('\\\\', '\\')


def join_backslash_continuations(text):
	# Macro bodies span physical lines via a trailing backslash-newline; joining them first lets
	# a single regex see the whole logical statement regardless of how the macro was formatted.
	return re.sub(r'\\\r?\n', ' ', text)


def extract_literal_messages(text):
	"""Every static_assert(<cond>, "<literal...literal>") whose message is a PURE (possibly
	multi-piece) string-literal concatenation -- no stringize operator involved."""
	messages = []
	for m in re.finditer(
		r'static_assert\s*\(.*?,\s*((?:' + STRING_LITERAL + r'\s*)+)\)',
		text,
		re.DOTALL,
	):
		literal_group = m.group(1)
		pieces = re.findall(STRING_LITERAL, literal_group)
		full = "".join(unescape(p[1:-1]) for p in pieces)
		messages.append(full)
	return messages


PREPROCESSOR_DIRECTIVES = {
	"include", "define", "undef", "pragma", "if", "ifdef", "ifndef", "else", "elif", "endif",
	"error", "warning", "line",
}


def extract_template_suffixes(text):
	"""Every `#NAME "suffix"` stringize-plus-literal pattern -- the shape a per-name X-macro
	check's message is built from. Captures the suffix literal only; the caller supplies
	candidate NAMEs separately, since the raw source never shows the expanded name. Excludes
	actual preprocessor directives (#include "path", #pragma "..."), which share the same
	`# word "literal"` shape but are not a stringize operator."""
	suffixes = []
	for m in re.finditer(r'#\s*(\w+)\s+((?:' + STRING_LITERAL + r'\s*)+)', text):
		word = m.group(1)
		if word.lower() in PREPROCESSOR_DIRECTIVES:
			continue
		pieces = re.findall(STRING_LITERAL, m.group(2))
		suffixes.append("".join(unescape(p[1:-1]) for p in pieces))
	return suffixes


def extract_candidate_names(text):
	"""Every ALL-CAPS SSLM_*-shaped identifier in the file -- a candidate substitution for a
	stringized macro parameter. Deliberately permissive (this is a completeness check, not a
	semantic one: it does not know which name the construction's own corruption targets)."""
	return sorted(set(re.findall(r'\bSSLM_[A-Z0-9_]+\b', text)))


def main():
	if len(sys.argv) != 3:
		print("usage: verify_negative_compile_marker_source.py <source_file> <marker_text>")
		return 2
	source_path, marker_text = sys.argv[1], sys.argv[2]

	try:
		with open(source_path, "r", encoding="utf-8", errors="replace") as f:
			raw_text = f.read()
	except OSError as e:
		print(f"verify_negative_compile_marker_source.py: cannot read {source_path}: {e}")
		return 1

	text = join_backslash_continuations(raw_text)

	literal_messages = extract_literal_messages(text)
	suffixes = extract_template_suffixes(text)
	names = extract_candidate_names(text)

	valid = set(literal_messages)
	for suffix in suffixes:
		for name in names:
			valid.add(name + suffix)

	if marker_text in valid:
		print(f"verify_negative_compile_marker_source.py: MARKER_TEXT is a complete, "
		      f"well-formed static_assert message for {source_path} (source-verified, not a "
		      f"substring match).")
		return 0

	print(f"verify_negative_compile_marker_source.py FAILED -- MARKER_TEXT does not equal any "
	      f"complete static_assert message this construction ({source_path}) can produce. This "
	      f"catches both an EMPTY marker and a MANGLED/TRUNCATED one (a hand-transcription that "
	      f"dropped a prefix or suffix) -- either passes a plain substring search against the "
	      f"compiler's own output vacuously, which is exactly the class this script exists to "
	      f"close.")
	print(f"  MARKER_TEXT given: {marker_text!r}")
	print(f"  literal messages found in source: {literal_messages!r}")
	print(f"  template suffixes found in source: {suffixes!r}")
	print(f"  candidate NAMEs found in source: {names!r}")
	return 1


if __name__ == "__main__":
	sys.exit(main())
